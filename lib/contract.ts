// Builds the collaboration agreement from a deal and its campaign.
// This is a DRAFT TEMPLATE for the prototype: it needs review by a qualified
// lawyer (and a CA for the tax clause) before anyone relies on it.
import type { Campaign, Creator, Deal, Poster } from "@/types";
import { dealTotal } from "./budget";
import {
  ORGANIC_USAGE,
  deliverableCount,
  usageLine,
  usageNotes,
  usageOptions,
} from "./campaign-options";
import { formatINR } from "./format";

export interface ContractSection {
  heading: string;
  lines: string[];
}
export const CONTRACT_DISCLAIMER =
  "Draft template generated by CollabKaro for this demo. It is not legal advice and is not legally binding in this prototype. Have a lawyer review it before using it for a real deal.";

const date = (iso: string) =>
  new Date(iso).toLocaleDateString("en-IN", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });

export function buildContract(
  deal: Deal,
  campaign: Campaign,
  creator: Creator,
  poster: Poster,
): { title: string; sections: ContractSection[] } {
  const brandName =
    campaign.brand && campaign.brand !== poster.name
      ? `${campaign.brand} (posted by ${poster.name})`
      : poster.name;
  const usageFees = deal.usageFees.filter((u) => u.amount > 0);
  const rights = campaign.usageRights ?? [];
  const exclusivity = rights.find((u) => u.kind === "exclusivity");
  const notes =
    usageNotes(campaign) || (!campaign.usageRights ? campaign.usage : "");
  const sections: ContractSection[] = [
    {
      heading: "1. Parties",
      lines: [
        `Brand: ${brandName}, ${poster.city}.`,
        `Creator: ${creator.name}, ${creator.city} (${creator.platforms.map((p) => `${p.name} ${p.handle}`).join(", ")}).`,
        "CollabKaro only connects the parties and is not a party to this agreement.",
      ],
    },
    {
      heading: "2. Campaign and brief",
      lines: [
        `Campaign: “${campaign.title.replace(/[.!?]+$/, "")}”.`,
        campaign.brief,
        ...(campaign.dos?.length
          ? [`The creator will: ${campaign.dos.join("; ")}.`]
          : []),
        ...(campaign.donts?.length
          ? [`The creator will not: ${campaign.donts.join("; ")}.`]
          : []),
      ],
    },
    {
      heading: "3. Deliverables and timeline",
      lines: [
        ...campaign.deliverables.map((d) => `• ${deliverableCount(d)}`),
        "Content is due 7 days after product delivery or brief confirmation, unless both parties agree otherwise in writing.",
        `The brand reviews content within 3 business days. The fee covers up to ${creator.revisions} rounds of reasonable revisions within the agreed brief.`,
      ],
    },
    {
      heading: "4. Fees and payment",
      lines: [
        `Creator fee: ${formatINR(deal.amount)}.`,
        ...usageFees.map(
          (u) =>
            `Usage fee (${usageOptions.find((o) => o.kind === u.kind)?.label ?? u.kind}): ${formatINR(u.amount)}.`,
        ),
        `Total payable to the creator: ${formatINR(dealTotal(deal))}, paid as follows:`,
        ...deal.milestones.map(
          (m) => `• ${m.label}: ${formatINR(m.amount)} (${m.percent}%)`,
        ),
        "The brand pays the creator directly. CollabKaro does not hold or transfer money in this version.",
        "Amounts exclude GST. Any tax deducted at source (TDS) as required by law may apply, and each party handles its own taxes.",
      ],
    },
    {
      heading: "5. Content ownership and usage rights",
      lines: [
        "The creator keeps copyright in the content. The brand receives a licence only for the uses and periods listed here.",
        ORGANIC_USAGE,
        ...rights.map((u) => `• ${usageLine(u)}`),
        ...(notes ? [notes] : []),
        "Any other use needs the creator’s written permission and may need an extra fee.",
      ],
    },
    {
      heading: "6. Disclosure",
      lines: [
        "Every post will carry a clear, upfront label such as “Ad”, “Paid partnership” or “Collaboration”, as required by the ASCI influencer guidelines and Indian consumer law. This also applies to ads run with the creator’s content.",
      ],
    },
    ...(exclusivity
      ? [
          {
            heading: "7. Exclusivity",
            lines: [
              `For ${exclusivity.days} days from the first post, the creator will not promote directly competing brands in the brand’s category.`,
            ],
          },
        ]
      : []),
    {
      heading: `${exclusivity ? 8 : 7}. Cancellation`,
      lines: [
        "Either party may cancel in writing. Fees for work already delivered and approved stay payable. Advances for work that was not delivered are refunded.",
      ],
    },
    {
      heading: `${exclusivity ? 9 : 8}. Confidentiality and disputes`,
      lines: [
        "Both parties keep unreleased campaign details private until the content goes live.",
        "The parties will first try to resolve any disagreement in good faith. This agreement is governed by the laws of India.",
      ],
    },
  ];
  return {
    title: `Collaboration agreement: ${campaign.title}`,
    sections: [
      ...sections,
      {
        heading: "Agreement date",
        lines: [`Terms prepared on ${date(deal.updatedAt)}.`],
      },
    ],
  };
}

const esc = (s: string) =>
  s.replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        c
      ]!,
  );
/** Opens a clean printable page so the user can print or "Save as PDF". */
export function printContract(
  doc: { title: string; sections: ContractSection[] },
  deal: Deal,
) {
  const sign = (label: string, s?: { name: string; at: string }) =>
    `<div class="sig"><strong>${label}</strong><span>${
      s
        ? `Signed by ${esc(s.name)} on ${esc(new Date(s.at).toLocaleString("en-IN"))}`
        : "Not signed yet"
    }</span></div>`;
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>${esc(doc.title)}</title>
<style>body{font:14px/1.6 Arial,sans-serif;color:#111;max-width:760px;margin:40px auto;padding:0 24px}
h1{font-size:22px}h2{font-size:15px;margin:22px 0 6px}p{margin:4px 0}
.note{font-size:12px;color:#555;border:1px solid #ccc;padding:10px;border-radius:6px}
.sigs{display:grid;grid-template-columns:1fr 1fr;gap:16px;margin-top:28px}
.sig{border-top:1px solid #333;padding-top:8px;display:grid;gap:4px}</style></head><body>
<h1>${esc(doc.title)}</h1><p class="note">${esc(CONTRACT_DISCLAIMER)}</p>
${doc.sections.map((s) => `<h2>${esc(s.heading)}</h2>${s.lines.map((l) => `<p>${esc(l)}</p>`).join("")}`).join("")}
<div class="sigs">${sign("Brand", deal.brandSignature)}${sign("Creator", deal.creatorSignature)}</div>
</body></html>`;
  const w = window.open("", "_blank");
  if (!w) return false;
  w.document.write(html);
  w.document.close();
  w.focus();
  w.print();
  return true;
}
